#!/usr/bin/env bash
# Writes setup.sql = all migrations + demo seed, for one paste into Supabase → SQL Editor.
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "-- Sports Hub: full database setup. Generated by supabase/bundle.sh — edit the migrations, not this file."
  echo "-- Paste once into Supabase Dashboard → SQL Editor → Run, on an empty project."
  for f in migrations/*.sql seed_demo.sql; do printf '\n-- ===== %s =====\n' "$f"; cat "$f"; done
} > setup.sql
